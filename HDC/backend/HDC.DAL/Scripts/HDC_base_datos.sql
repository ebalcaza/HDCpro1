/* Cabecera del registro de emisiones: un domicilio en un período (mes) */
CREATE TABLE IF NOT EXISTS registros
(
    id_registro               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_domicilio              BIGINT NOT NULL,
    id_usuario_carga          BIGINT NOT NULL,
    periodo                   DATE NOT NULL,
    observaciones             VARCHAR(500) NULL,
    total_kg_co2              NUMERIC(18,6) NOT NULL DEFAULT 0,
    fecha_creacion            TIMESTAMP(3) NOT NULL DEFAULT LOCALTIMESTAMP(3),
    fecha_ultima_modificacion TIMESTAMP(3) NOT NULL DEFAULT LOCALTIMESTAMP(3),
    CONSTRAINT pk_registros PRIMARY KEY (id_registro),
    CONSTRAINT fk_registros_domicilio FOREIGN KEY (id_domicilio) REFERENCES domicilio (id_domicilio),
    CONSTRAINT fk_registros_usuario_carga FOREIGN KEY (id_usuario_carga) REFERENCES usuario (id_usuario),
    -- El período siempre es el día 1 del mes
    CONSTRAINT ck_registros_periodo CHECK (EXTRACT(DAY FROM periodo) = 1)
);

/* Detalle: cada consumo de una fuente de emisión dentro del registro */
CREATE TABLE IF NOT EXISTS detalle_registro
(
    id_detalle           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_registro          BIGINT NOT NULL,
    id_fuente_emision    BIGINT NOT NULL,
    consumo              NUMERIC(18,4) NOT NULL,
    valor_factor_emision NUMERIC(18,6) NOT NULL,
    kg_co2               NUMERIC(18,6) NOT NULL,
    CONSTRAINT pk_detalle_registro PRIMARY KEY (id_detalle),
    CONSTRAINT fk_detalle_registro FOREIGN KEY (id_registro) REFERENCES registros (id_registro) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_fuente FOREIGN KEY (id_fuente_emision) REFERENCES fuente_emision (id_fuente_emision),
    CONSTRAINT ck_detalle_consumo CHECK (consumo > 0)
);

/* Colaboración: el titular del domicilio invita a otro usuario a cargar
   emisiones de ciertos tipos durante un rango de períodos */
CREATE TABLE IF NOT EXISTS colaboracion
(
    id_colaboracion        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_domicilio           BIGINT NOT NULL,
    id_usuario_colaborador BIGINT NOT NULL,
    periodo_desde          DATE NOT NULL,
    periodo_hasta          DATE NULL,
    estado                 VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    mensaje                VARCHAR(500) NULL,
    fecha_invitacion       TIMESTAMP(3) NOT NULL DEFAULT LOCALTIMESTAMP(3),
    fecha_respuesta        TIMESTAMP(3) NULL,
    CONSTRAINT pk_colaboracion PRIMARY KEY (id_colaboracion),
    CONSTRAINT fk_colaboracion_domicilio FOREIGN KEY (id_domicilio) REFERENCES domicilio (id_domicilio) ON DELETE CASCADE,
    CONSTRAINT fk_colaboracion_usuario FOREIGN KEY (id_usuario_colaborador) REFERENCES usuario (id_usuario),
    -- PENDIENTE: invitación por email esperando respuesta del invitado
    -- SOLICITADA: alguien se sumó con el código de una convocatoria y espera la aprobación del titular (v2.2)
    CONSTRAINT ck_colaboracion_estado CHECK (estado IN ('PENDIENTE', 'SOLICITADA', 'ACEPTADA', 'RECHAZADA', 'REVOCADA')),
    CONSTRAINT ck_colaboracion_periodos CHECK (periodo_hasta IS NULL OR periodo_hasta >= periodo_desde)
);

CREATE TABLE IF NOT EXISTS colaboracion_tipo_emision
(
    id_colaboracion BIGINT NOT NULL,
    id_tipo_emision BIGINT NOT NULL,
    CONSTRAINT pk_colaboracion_tipo PRIMARY KEY (id_colaboracion, id_tipo_emision),
    CONSTRAINT fk_colabtipo_colaboracion FOREIGN KEY (id_colaboracion) REFERENCES colaboracion (id_colaboracion) ON DELETE CASCADE,
    CONSTRAINT fk_colabtipo_tipo FOREIGN KEY (id_tipo_emision) REFERENCES tipo_emision (id_tipo_emision)
);

/* Convocatoria (v2.2): el titular de un domicilio publica un CÓDIGO para que muchas personas
   se sumen como colaboradoras sin invitarlas una por una. Define para todos sus miembros
   qué tipos de emisión pueden cargar y en qué períodos.
   Estados: ABIERTA (se puede sumar gente con el código), CERRADA (no entra nadie nuevo,
   los miembros aceptados siguen cargando), FINALIZADA (nadie carga más; no se reabre). */
CREATE TABLE IF NOT EXISTS convocatoria
(
    id_convocatoria       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_domicilio          BIGINT NOT NULL,
    nombre                VARCHAR(150) NOT NULL,
    descripcion           VARCHAR(500) NULL,
    codigo                VARCHAR(8) NOT NULL,      -- 8 caracteres sin guion; se muestra como XXXX-XXXX
    periodo_desde         DATE NOT NULL,
    periodo_hasta         DATE NULL,
    aprobacion_automatica BOOLEAN NOT NULL DEFAULT FALSE,
    estado                VARCHAR(20) NOT NULL DEFAULT 'ABIERTA',
    fecha_creacion        TIMESTAMP(3) NOT NULL DEFAULT LOCALTIMESTAMP(3),
    fecha_modificacion    TIMESTAMP(3) NULL,
    CONSTRAINT pk_convocatoria PRIMARY KEY (id_convocatoria),
    CONSTRAINT uq_convocatoria_codigo UNIQUE (codigo),
    CONSTRAINT fk_convocatoria_domicilio FOREIGN KEY (id_domicilio) REFERENCES domicilio (id_domicilio) ON DELETE CASCADE,
    CONSTRAINT ck_convocatoria_estado CHECK (estado IN ('ABIERTA', 'CERRADA', 'FINALIZADA')),
    CONSTRAINT ck_convocatoria_periodos CHECK (periodo_hasta IS NULL OR periodo_hasta >= periodo_desde)
);

CREATE TABLE IF NOT EXISTS convocatoria_tipo_emision
(
    id_convocatoria BIGINT NOT NULL,
    id_tipo_emision BIGINT NOT NULL,
    CONSTRAINT pk_convocatoria_tipo PRIMARY KEY (id_convocatoria, id_tipo_emision),
    CONSTRAINT fk_convtipo_convocatoria FOREIGN KEY (id_convocatoria) REFERENCES convocatoria (id_convocatoria) ON DELETE CASCADE,
    CONSTRAINT fk_convtipo_tipo FOREIGN KEY (id_tipo_emision) REFERENCES tipo_emision (id_tipo_emision)
);

/* v2.2: columnas nuevas de colaboracion (ADD COLUMN IF NOT EXISTS: sirve para bases nuevas y existentes)
   - id_convocatoria: si la colaboración nació de una convocatoria (NULL = invitación por email).
     Los tipos de emisión de esas colaboraciones son los de la convocatoria.
   - id_usuario_baja: quién la rechazó o finalizó (el titular o el propio colaborador).
     Si fue el titular, la persona no puede volver a sumarse con el código. */
ALTER TABLE colaboracion ADD COLUMN IF NOT EXISTS id_convocatoria BIGINT NULL
    CONSTRAINT fk_colaboracion_convocatoria REFERENCES convocatoria (id_convocatoria) ON DELETE CASCADE;
ALTER TABLE colaboracion ADD COLUMN IF NOT EXISTS id_usuario_baja BIGINT NULL
    CONSTRAINT fk_colaboracion_usuario_baja REFERENCES usuario (id_usuario);

/* Bases creadas antes de la v2.2 tienen la restricción de estados vieja (sin SOLICITADA): se reemplaza
   solo si hace falta (un bloque DO permite usar IF en un script de PostgreSQL). */
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'ck_colaboracion_estado'
                     AND pg_get_constraintdef(oid) LIKE '%SOLICITADA%') THEN
        ALTER TABLE colaboracion DROP CONSTRAINT IF EXISTS ck_colaboracion_estado;
        ALTER TABLE colaboracion ADD CONSTRAINT ck_colaboracion_estado
            CHECK (estado IN ('PENDIENTE', 'SOLICITADA', 'ACEPTADA', 'RECHAZADA', 'REVOCADA'));
    END IF;
END $$;

