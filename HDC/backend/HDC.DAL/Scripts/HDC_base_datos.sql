SELECT setval(pg_get_serial_sequence('tipo_emision', 'id_tipo_emision'), (SELECT COALESCE(MAX(id_tipo_emision), 1) FROM tipo_emision));


/* =====================================================================
   3. ÍNDICES DE RENDIMIENTO
   ---------------------------------------------------------------------
   PostgreSQL NO crea índices automáticamente para las claves foráneas
   (solo para PRIMARY KEY y UNIQUE). Sin estos índices, cada JOIN o WHERE
   por esas columnas recorre la tabla completa ("sequential scan").

   INCLUDE (...) agrega columnas a la hoja del índice: si una consulta solo
   necesita esas columnas, PostgreSQL la resuelve leyendo el índice, sin ir
   a la tabla ("index-only scan").
   ===================================================================== */

/* Registros de un domicilio por período (listados y validación de período repetido) */
CREATE INDEX IF NOT EXISTS ix_registros_domicilio_periodo ON registros (id_domicilio, periodo);

/* Detalles de un registro: se usan al abrir un registro, al listar y en todas las sumas del Dashboard/reportes */
CREATE INDEX IF NOT EXISTS ix_detalle_registro_registro ON detalle_registro (id_registro)
    INCLUDE (id_fuente_emision, consumo, kg_co2);

/* Agrupar / filtrar consumos por fuente de emisión (reportes por fuente, tipo o alcance) */
CREATE INDEX IF NOT EXISTS ix_detalle_registro_fuente ON detalle_registro (id_fuente_emision)
    INCLUDE (id_registro, consumo, kg_co2);

/* Domicilios de un usuario: "Mis domicilios", Dashboard y la visibilidad de "Mis emisiones" */
CREATE INDEX IF NOT EXISTS ix_domicilio_usuario ON domicilio (id_usuario)
    INCLUDE (fecha_baja, total_kg_co2);

/* Filtros geográficos de los reportes (ciudad → distrito → provincia) */
CREATE INDEX IF NOT EXISTS ix_domicilio_ciudad ON domicilio (id_ciudad);

/* Registros cargados por un colaborador (también aparecen en su "Mis emisiones") */
CREATE INDEX IF NOT EXISTS ix_registros_usuario_carga ON registros (id_usuario_carga)
    INCLUDE (id_domicilio, periodo, total_kg_co2);

/* Colaboraciones de un domicilio por estado (validar quién puede cargar, conteo de colaboradores activos) */
CREATE INDEX IF NOT EXISTS ix_colaboracion_domicilio_estado ON colaboracion (id_domicilio, estado);

/* Colaboraciones recibidas por un usuario */
CREATE INDEX IF NOT EXISTS ix_colaboracion_colaborador ON colaboracion (id_usuario_colaborador);

