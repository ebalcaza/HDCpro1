/* Carga de un traslado: lo que declaró la persona de una sola vez. Genera un registro por cada mes
   cubierto, para que los gráficos y filtros mensuales sigan siendo correctos. Editarla o eliminarla
   afecta a todos sus registros. El factor queda congelado, igual que en detalle_registro. */
CREATE TABLE IF NOT EXISTS carga_traslado
(
    id_carga_traslado    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_domicilio         BIGINT NOT NULL,
    id_usuario_carga     BIGINT NOT NULL,
    id_convocatoria_rol  BIGINT NULL,
    periodicidad         VARCHAR(20) NOT NULL,
    periodo_desde        DATE NOT NULL,
    periodo_hasta        DATE NOT NULL,              -- último mes cargado: nunca posterior al mes en curso
    semanas              NUMERIC(5,2) NOT NULL,      -- semanas del período completo
    cantidad_personas    INT NOT NULL DEFAULT 1,     -- el colaborador carga por sí mismo (1); el titular puede cargar un grupo
    fecha_creacion       TIMESTAMP(3) NOT NULL DEFAULT LOCALTIMESTAMP(3),
    CONSTRAINT pk_carga_traslado PRIMARY KEY (id_carga_traslado),
    CONSTRAINT fk_carga_domicilio FOREIGN KEY (id_domicilio) REFERENCES domicilio (id_domicilio) ON DELETE CASCADE,
    CONSTRAINT fk_carga_usuario FOREIGN KEY (id_usuario_carga) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_carga_rol FOREIGN KEY (id_convocatoria_rol) REFERENCES convocatoria_rol (id_convocatoria_rol) ON DELETE SET NULL,
    CONSTRAINT ck_carga_periodos CHECK (periodo_hasta >= periodo_desde)
);

ALTER TABLE registros ADD COLUMN IF NOT EXISTS id_carga_traslado BIGINT NULL
    CONSTRAINT fk_registros_carga REFERENCES carga_traslado (id_carga_traslado) ON DELETE CASCADE;

/* =====================================================================
   v2.8 - Período definido por el organizador y varios medios por carga
   ---------------------------------------------------------------------
   semanas_traslado: semanas de actividad del período de la convocatoria.
   periodicidad PERIODO: carga de todo el período de una convocatoria.
   meses_periodo: meses del período completo, aunque la carga cubra uno solo.
   carga_traslado_medio: un medio con su distancia, días y factor congelado.
   ===================================================================== */
ALTER TABLE convocatoria ADD COLUMN IF NOT EXISTS semanas_traslado NUMERIC(5,2) NULL;
ALTER TABLE carga_traslado ADD COLUMN IF NOT EXISTS id_convocatoria BIGINT NULL
    CONSTRAINT fk_carga_convocatoria REFERENCES convocatoria (id_convocatoria) ON DELETE SET NULL;
ALTER TABLE carga_traslado ADD COLUMN IF NOT EXISTS meses_periodo INT NOT NULL DEFAULT 1;

CREATE TABLE IF NOT EXISTS carga_traslado_medio
(
    id_carga_traslado_medio BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_carga_traslado    BIGINT NOT NULL,
    id_fuente_emision    BIGINT NOT NULL,
    distancia_km         NUMERIC(10,2) NOT NULL,     -- ida y vuelta, por día de asistencia
    dias_semana          NUMERIC(3,1) NOT NULL,
    valor_factor_emision NUMERIC(18,6) NOT NULL,
    CONSTRAINT pk_carga_traslado_medio PRIMARY KEY (id_carga_traslado_medio),
    CONSTRAINT uq_carga_medio UNIQUE (id_carga_traslado, id_fuente_emision),
    CONSTRAINT fk_medio_carga FOREIGN KEY (id_carga_traslado) REFERENCES carga_traslado (id_carga_traslado) ON DELETE CASCADE,
    CONSTRAINT fk_medio_fuente FOREIGN KEY (id_fuente_emision) REFERENCES fuente_emision (id_fuente_emision),
    CONSTRAINT ck_medio_valores CHECK (distancia_km > 0 AND dias_semana > 0 AND dias_semana <= 7)
);

/* Bases con traslados de la v2.6: cada carga tenía un solo medio en sus propias columnas. Se pasa a la tabla nueva
   y se borran esas columnas. Al ejecutar el script de nuevo, las columnas ya no existen y este bloque no hace nada. */
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_name = 'carga_traslado' AND column_name = 'id_fuente_emision') THEN
        INSERT INTO carga_traslado_medio (id_carga_traslado, id_fuente_emision, distancia_km, dias_semana, valor_factor_emision)
        SELECT id_carga_traslado, id_fuente_emision, distancia_km, dias_semana, valor_factor_emision FROM carga_traslado;

        UPDATE carga_traslado SET meses_periodo = CASE periodicidad WHEN 'ANUAL' THEN 12 WHEN 'SEMESTRAL' THEN 6 ELSE 1 END;

        UPDATE carga_traslado x SET id_convocatoria = r.id_convocatoria
        FROM convocatoria_rol r WHERE r.id_convocatoria_rol = x.id_convocatoria_rol;

        ALTER TABLE carga_traslado DROP COLUMN id_fuente_emision, DROP COLUMN distancia_km,
            DROP COLUMN dias_semana, DROP COLUMN valor_factor_emision;
    END IF;
END $$;

ALTER TABLE carga_traslado DROP CONSTRAINT IF EXISTS ck_carga_periodicidad;
ALTER TABLE carga_traslado ADD CONSTRAINT ck_carga_periodicidad
    CHECK (periodicidad IN ('MENSUAL', 'SEMESTRAL', 'ANUAL', 'PERIODO'));
ALTER TABLE carga_traslado DROP CONSTRAINT IF EXISTS ck_carga_valores;
ALTER TABLE carga_traslado ADD CONSTRAINT ck_carga_valores
    CHECK (semanas > 0 AND cantidad_personas > 0 AND meses_periodo > 0);

/* =====================================================================
   v2.9 - Factores de viajes calculados y rol recordado
   ---------------------------------------------------------------------
