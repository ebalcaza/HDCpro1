/* =====================================================================
   HUELLA DE CARBONO (HDC) - Script ÚNICO de base de datos (PostgreSQL)
   ---------------------------------------------------------------------
   Contiene, en este orden:
     1. Esquema (tablas)
     2. Datos iniciales (roles, permisos y catálogos)
     3. Índices de rendimiento

   Es IDEMPOTENTE: cada tabla, dato inicial e índice se crea solo si no
   existe. Por eso la API (InicializadorBaseDatos) lo ejecuta en CADA
   arranque: en una base vacía crea todo, y en una base existente solo
   agrega lo que falte (por ejemplo, un índice o una tabla nueva).

   Uso manual (psql / pgAdmin / DBeaver): crear la base y ejecutarlo en ella:
       CREATE DATABASE huellacarbono;
       \c huellacarbono
       \i HDC_base_datos.sql

   Convenciones de PostgreSQL usadas:
   - Nombres de tablas y columnas en minúscula y SIN comillas. PostgreSQL
     pasa a minúscula todo identificador sin comillas; el DbContext
     (HdcDbContext) mapea las entidades a estos mismos nombres.
   - PK autonuméricas con "GENERATED BY DEFAULT AS IDENTITY" (equivale al
     IDENTITY de SQL Server, pero permite insertar ids fijos en los datos
     iniciales sin activar nada especial).
   - VARCHAR para textos (en PostgreSQL todo texto es Unicode, no hay
     NVARCHAR), TEXT para textos largos, BOOLEAN para verdadero/falso.
   - TIMESTAMP(0) = fecha y hora sin segundos fraccionarios
     (reemplaza a SMALLDATETIME); TIMESTAMP(3) reemplaza a DATETIME.
   - Excepto PROVINCIA/DISTRITO/CIUDAD, que usan el id de la API georef.
   ===================================================================== */


