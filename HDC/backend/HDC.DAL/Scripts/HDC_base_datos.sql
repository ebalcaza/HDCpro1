/* Convocatoria (v2.2): el titular de un domicilio publica un CÓDIGO para que muchas personas
   se sumen como colaboradoras sin invitarlas una por una. Define para todos sus miembros
   qué tipos de emisión pueden cargar y en qué períodos.
   Estados: ABIERTA (se puede sumar gente con el código), CERRADA (no entra nadie nuevo,
   los miembros aceptados siguen cargando), FINALIZADA (nadie carga más; no se reabre). */
CREATE TABLE IF NOT EXISTS convocatoria
(
    id_convocatoria       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_domicilio          BIGINT NOT NULL,
    nombre                VARCHAR(150) NOT NULL,
    descripcion           VARCHAR(500) NULL,
    codigo                VARCHAR(8) NOT NULL,      -- 8 caracteres sin guion; se muestra como XXXX-XXXX
    periodo_desde         DATE NOT NULL,
    periodo_hasta         DATE NULL,
    aprobacion_automatica BOOLEAN NOT NULL DEFAULT FALSE,
    estado                VARCHAR(20) NOT NULL DEFAULT 'ABIERTA',
    fecha_creacion        TIMESTAMP(3) NOT NULL DEFAULT LOCALTIMESTAMP(3),
    fecha_modificacion    TIMESTAMP(3) NULL,
    CONSTRAINT pk_convocatoria PRIMARY KEY (id_convocatoria),
    CONSTRAINT uq_convocatoria_codigo UNIQUE (codigo),
    CONSTRAINT fk_convocatoria_domicilio FOREIGN KEY (id_domicilio) REFERENCES domicilio (id_domicilio) ON DELETE CASCADE,
    CONSTRAINT ck_convocatoria_estado CHECK (estado IN ('ABIERTA', 'CERRADA', 'FINALIZADA')),
    CONSTRAINT ck_convocatoria_periodos CHECK (periodo_hasta IS NULL OR periodo_hasta >= periodo_desde)
);

CREATE TABLE IF NOT EXISTS convocatoria_tipo_emision
(
    id_convocatoria BIGINT NOT NULL,
    id_tipo_emision BIGINT NOT NULL,
    CONSTRAINT pk_convocatoria_tipo PRIMARY KEY (id_convocatoria, id_tipo_emision),
    CONSTRAINT fk_convtipo_convocatoria FOREIGN KEY (id_convocatoria) REFERENCES convocatoria (id_convocatoria) ON DELETE CASCADE,
    CONSTRAINT fk_convtipo_tipo FOREIGN KEY (id_tipo_emision) REFERENCES tipo_emision (id_tipo_emision)
);

/* v2.2: columnas nuevas de colaboracion (ADD COLUMN IF NOT EXISTS: sirve para bases nuevas y existentes)
