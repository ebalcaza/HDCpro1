    CONSTRAINT fk_colaboracion_usuario_baja REFERENCES usuario (id_usuario);

/* =====================================================================
   v2.6 - Catálogo definitivo, traslados y roles de convocatoria
   ---------------------------------------------------------------------
   modo_carga indica qué datos se piden para las fuentes de cada tipo:
     CONSUMO  = solo la cantidad (gas, electricidad, residuos...)
     VEHICULO = litros y, opcionalmente, los km recorridos
     TRASLADO = medio de transporte, distancia, días por semana y período
     VIAJE    = km y fecha; se guarda como dato, con factor 0
   Las columnas nuevas de detalle_registro solo se usan en esos modos.
   ===================================================================== */
ALTER TABLE tipo_emision ADD COLUMN IF NOT EXISTS modo_carga VARCHAR(20) NOT NULL DEFAULT 'CONSUMO';
ALTER TABLE tipo_emision DROP CONSTRAINT IF EXISTS ck_tipo_emision_modo;
ALTER TABLE tipo_emision ADD CONSTRAINT ck_tipo_emision_modo
    CHECK (modo_carga IN ('CONSUMO', 'VEHICULO', 'TRASLADO', 'VIAJE'));

ALTER TABLE detalle_registro ADD COLUMN IF NOT EXISTS kilometros NUMERIC(18,2) NULL;
ALTER TABLE detalle_registro ADD COLUMN IF NOT EXISTS fecha_viaje DATE NULL;

