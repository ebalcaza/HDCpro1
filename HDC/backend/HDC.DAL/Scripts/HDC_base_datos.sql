/* Las tablas con ids fijos (rol, alcance, unidad_medida, tipo_emision) se
   cargaron indicando el id a mano: hay que mover su secuencia IDENTITY
   para que el próximo alta desde la aplicación no repita un id existente.
   setval(..., MAX(id)) deja la secuencia en el último id usado. */
