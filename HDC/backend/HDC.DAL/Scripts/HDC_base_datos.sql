/* Recuperación de contraseña: un pedido por cada "Olvidé mi contraseña".
   Se guarda el HASH SHA-256 del token (64 caracteres hex), nunca el token:
   si alguien leyera la tabla no podría usar los links enviados por email.
   Un pedido sirve una sola vez (fecha_uso) y vence en fecha_expiracion. */
CREATE TABLE IF NOT EXISTS recuperacion_contrasena
(
    id_recuperacion  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario       BIGINT NOT NULL,
    token_hash       CHAR(64) NOT NULL,
    fecha_creacion   TIMESTAMP(3) NOT NULL DEFAULT LOCALTIMESTAMP(3),
    fecha_expiracion TIMESTAMP(3) NOT NULL,
    fecha_uso        TIMESTAMP(3) NULL,
    CONSTRAINT pk_recuperacion_contrasena PRIMARY KEY (id_recuperacion),
    CONSTRAINT uq_recuperacion_token UNIQUE (token_hash),
    CONSTRAINT fk_recuperacion_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE
);

