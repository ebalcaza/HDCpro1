    WHERE x.id_convocatoria = c.id_convocatoria AND x.id_usuario_carga = c.id_usuario_colaborador AND x.id_convocatoria_rol IS NOT NULL
    ORDER BY x.fecha_creacion DESC, x.id_carga_traslado DESC LIMIT 1)
WHERE c.id_convocatoria IS NOT NULL AND c.id_convocatoria_rol IS NULL;

/* =====================================================================
   v2.10 - Cada aporte pertenece a una convocatoria
   ---------------------------------------------------------------------
   Una persona puede estar en varias convocatorias del mismo domicilio. Los aportes se buscaban por persona y
   domicilio, así que lo cargado en una aparecía también en las demás. Al crear la columna se completa lo existente:
   los traslados toman la convocatoria de su carga; el resto, la que cubría ese mes y esos tipos cuando se cargó.
   ===================================================================== */
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_name = 'registros' AND column_name = 'id_convocatoria') THEN
        ALTER TABLE registros ADD COLUMN id_convocatoria BIGINT NULL
            CONSTRAINT fk_registros_convocatoria REFERENCES convocatoria (id_convocatoria) ON DELETE SET NULL;

        UPDATE registros r SET id_convocatoria = x.id_convocatoria
        FROM carga_traslado x
        WHERE x.id_carga_traslado = r.id_carga_traslado AND x.id_convocatoria IS NOT NULL;

        UPDATE registros r
        SET id_convocatoria = (
            SELECT m.id_convocatoria FROM colaboracion m
            JOIN convocatoria cv ON cv.id_convocatoria = m.id_convocatoria
            WHERE m.id_usuario_colaborador = r.id_usuario_carga AND m.id_domicilio = r.id_domicilio
              AND m.fecha_invitacion <= r.fecha_creacion
              AND cv.periodo_desde <= r.periodo AND (cv.periodo_hasta IS NULL OR cv.periodo_hasta >= r.periodo)
              AND NOT EXISTS (
                  SELECT 1 FROM detalle_registro d
                  JOIN fuente_emision f ON f.id_fuente_emision = d.id_fuente_emision
                  WHERE d.id_registro = r.id_registro
                    AND NOT EXISTS (SELECT 1 FROM convocatoria_tipo_emision t
                                    WHERE t.id_convocatoria = cv.id_convocatoria AND t.id_tipo_emision = f.id_tipo_emision))
            ORDER BY m.fecha_invitacion DESC LIMIT 1)
        WHERE r.id_convocatoria IS NULL;
    END IF;
END $$;

